/** Python str.casefold()：完整大小写折叠（ß → ss、ς → σ 等），不做 final sigma 等上下文处理。 */
export function pythonCasefold(text: string): string {
  let output = '';
  for (const char of text) output += CASEFOLD.get(char.codePointAt(0)!) ?? char.toLowerCase();
  return output;
}

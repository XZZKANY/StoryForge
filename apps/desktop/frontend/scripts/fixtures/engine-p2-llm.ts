import { isTauri } from '@tauri-apps/api/core';
import {
  buildChatPayload,
  callLlm,
  streamChatCompletions,
  type HttpRequest,
  type LlmContext,
} from '@storyforge/engine';
import { nativeHttpPort, nativeLlmSource } from '../../src/lib/engine/llm';

function assert(condition: unknown, message: string): asserts condition {
  if (!condition) throw new Error(message);
}

const describe = (error: unknown) => ({
  name: error instanceof Error ? error.name : typeof error,
  message: error instanceof Error ? error.message : String(error),
});

async function readAll(body: AsyncIterable<Uint8Array>): Promise<string> {
  const decoder = new TextDecoder();
  let text = '';
  for await (const chunk of body) text += decoder.decode(chunk, { stream: true });
  return text + decoder.decode();
}

// Synthetic local servers only: the key under test is generated by the harness.
async function runLlmProbe(input: { foreignUrl: string }) {
  assert(isTauri(), 'LLM probe requires the real Native host');
  const { source, secrets } = await nativeLlmSource('main');
  const polish = await nativeLlmSource('polish');
  const port = nativeHttpPort('main');
  const ctx: LlmContext = {
    http: port,
    clock: () => performance.now() / 1000,
    wait: (seconds) => new Promise((resolve) => setTimeout(resolve, seconds * 1000)),
    random: () => 0.5,
    appVersion: '0.0.0-p2-probe',
    secrets,
  };
  const base = source.STORYFORGE_LLM_BASE_URL;
  assert(typeof base === 'string' && base, 'Probe source has no base URL');
  const credential = secrets.values[0];
  assert(credential, 'Probe source has no credential placeholder');

  const startedAt = Date.now();
  const deltas: { text: string; receivedAt: number }[] = [];
  let done: unknown = null;
  const payload = buildChatPayload(source, {
    messages: [{ role: 'user', content: '合成探针' }],
    stream: true,
  });
  for await (const frame of streamChatCompletions(source, payload, {}, ctx)) {
    if (frame.type === 'delta') deltas.push({ text: String(frame.text), receivedAt: Date.now() });
    if (frame.type === 'done') done = frame;
  }
  const failure = await callLlm(source, { systemPrompt: 's', userPrompt: 'u' }, ctx).then(
    () => null,
    describe,
  );
  const models = await port.send({
    url: `${base}/models`,
    method: 'GET',
    headers: { Authorization: `Bearer ${credential}` },
    body: null,
    timeoutSeconds: 10,
  });
  const modelsBody = await readAll(models.body);
  const refuse = (request: HttpRequest) => port.send(request).then(() => null, describe);
  const refusals = {
    foreign: await refuse({
      url: input.foreignUrl,
      method: 'GET',
      headers: { Authorization: `Bearer ${credential}` },
      body: null,
      timeoutSeconds: 5,
    }),
    header: await refuse({
      url: `${base}/models`,
      method: 'GET',
      headers: { 'X-Trace': credential },
      body: null,
      timeoutSeconds: 5,
    }),
  };
  const slow = await port.send({
    url: `${base}/slow`,
    method: 'GET',
    headers: {},
    body: null,
    timeoutSeconds: 10,
  });
  const first = await slow.body[Symbol.asyncIterator]().next();
  slow.close();
  return {
    native: isTauri(),
    source,
    polishSource: polish.source,
    secrets: secrets.values,
    startedAt,
    deltas,
    done,
    failure,
    models: { status: models.status, headers: models.headers, body: modelsBody },
    refusals,
    slow: {
      first: first.done ? null : new TextDecoder().decode(first.value),
      closedAt: Date.now(),
    },
  };
}

declare global {
  interface Window {
    __ENGINE_P2_LLM__: { runLlmProbe: typeof runLlmProbe };
  }
}
window.__ENGINE_P2_LLM__ = { runLlmProbe };
document.documentElement.dataset.engineP2LlmReady = 'true';
